/**
 * Товар каталога.
 *
 * @typedef {object} Product
 * @property {number} id Номер записи. Постоянный: по нему хранится корзина.
 * @property {string} name Название как его ввёл владелец.
 * @property {string} cat id категории. Нет такой категории — товар не покажется.
 * @property {number|null} old Старая цена. Больше текущей — на карточке скидка.
 * @property {boolean} stock false — «Нет в наличии», кнопка выключена.
 * @property {number} pop Порядок в сортировке «по популярности», по убыванию.
 * @property {boolean} isNew Плашка «Новинка». Ставит владелец галочкой.
 * @property {string} img Иконка-заглушка, когда фотографии нет.
 * @property {number} [price] Цена в рублях. Ключа нет — карточка покажет
 *   «Цена по запросу»: тема не отдаёт цену, которую владелец не заполнил.
 * @property {string} [url] Адрес страницы товара от WordPress. Без него
 *   карточка ведёт на макет tovar.html — так работает статическая сборка.
 * @property {string} [photo] Адрес фотографии.
 * @property {string} [srcset] Та же фотография в других ширинах.
 * @property {string} [sizes] Своё значение sizes. Без него подставляется
 *   размер под сетку каталога.
 * @property {Shot[]} [photos] Остальные снимки — только в демо-наборе:
 *   на живом сайте галерею печатает тема, а не браузер.
 * @property {Spec[]} [specs] Характеристики. Ключа нет вовсе, если их нет:
 *   пустой массив нарисовал бы заголовок над пустотой.
 */

// Все фотографии карточек разом. Забираем их пачкой, а не сорока импортами
// руками; Vite подставит адреса с хешами при сборке.
const FILES = import.meta.glob('../img/cards/*.webp', { eager: true, query: '?url', import: 'default' });

// Каждое фото заготовлено в трёх ширинах. У части исходников не хватило
// разрешения на 1600px — такого файла просто нет, и в srcset он не попадёт.
// В photo кладём средний размер: это то, что увидят браузеры постарше,
// не умеющие выбирать по srcset.
// Снимков у товара может быть несколько: файлы называются slug-1-400.webp,
// slug-2-400.webp и так далее. Порядок задан номером в имени — как их
// пронумеровал поставщик, так и покажем.
function shots(slug, count) {
  if (1 === count) {
    const one = shot(slug);
    return one.photo ? [one] : [];
  }

  return Array.from({ length: count }, (_, i) => shot(`${ slug }-${ i + 1 }`))
    .filter((s) => s.photo);
}

function shot(slug) {
  const found = [400, 800, 1600]
    .map((w) => [w, FILES[`../img/cards/${ slug }-${ w }.webp`]])
    .filter(([, url]) => url);
  if (!found.length) {
    return {};
  }
  const mid = found.find(([w]) => w === 800) ?? found[found.length - 1];
  return {
    photo: mid[1],
    srcset: found.map(([w, url]) => `${ url } ${ w }w`).join(', '),
  };
}

