// Читаем данные из разметки. Возвращаем null, только если блока нет вовсе
// или он не разбирается: это значит, что WordPress тут не участвует — открыт
// макет, — и тогда показываем демонстрационный набор.
//
// Пустые массивы — это полноценный ответ WordPress «товаров нет», и подменять
// его нельзя. Раньше в проверке стояло ещё categories.length > 0, и пустой
// каталог считался негодным: когда подрядчик удалил товары, на живой сайт
// выехали девять демо-диванов с ценами, которых в админке нет, а ссылки повели
// на макетный tovar.html и возвращали посетителя на главную. Пустая витрина
// честнее выдуманных товаров — по тому же правилу, по которому в проекте
// не считаются плашки «Новинка» без даты.
function fromPage() {
  const el = document.getElementById('catalog-data');
  if (!el) {
    return null;
  }
  try {
    const data = JSON.parse(el.textContent);
    const ok = Array.isArray(data.categories) && Array.isArray(data.products);
    return ok ? data : null;
  } catch {
    return null;
  }
}

