// ─── Утилиты ───

/**
 * Число как цена в рублях: 78990 -> «78 990 ₽».
 *
 * Между числом и ₽ стоит неразрывный пробел (код U+00A0), иначе знак рубля
 * переносится на следующую строку и цена рвётся пополам.
 *
 * @param {number} n Цена в рублях.
 * @returns {string} Цена со знаком рубля.
 */
export const fmt = (n) => `${n.toLocaleString('ru-RU')}\u00A0₽`;

// Режим прокрутки с учётом настройки ОС «уменьшить движение».
export const smooth = matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth';

/**
 * Экранирует текст, который попадает в HTML-шаблоны карточек.
 *
 * Пока товары лежали в коде, этого не требовалось — там всё было написано
 * нами. Из CMS приходит что угодно: кавычка в названии «Диван "Зевс"»
 * разорвала бы атрибут alt, а угловая скобка — всю разметку карточки.
 *
 * @param {unknown} v Что угодно из CMS, из адреса или из хранилища.
 * @returns {string} Строка, безопасная внутри разметки и внутри атрибута.
 */
export const esc = (v) => String(v).replace(/[&<>"']/g, (c) => `&#${ c.charCodeAt(0) };`);

// Ближайший подходящий элемент от места нажатия.
//
// Обёртка нужна из-за типов, а не из-за логики: в описании DOM e.target — это
// EventTarget, у которого нет closest, а closest обещает Element, у которого
// нет dataset. Без приведения редактор молчит и про то, и про другое, а с ним
// подчёркивает опечатку в имени data-атрибута сразу. Одним местом вместо
// девяти: то же приведение, повторённое в каждом обработчике, рано или поздно
// разошлось бы.
/**
 * @param {Event} e Событие мыши, указателя или клавиатуры.
 * @param {string} selector Селектор искомого элемента или его предка.
 * @returns {HTMLElement} Найденный элемент или null, если нажали мимо.
 */
export const hit = (e, selector) =>
  /** @type {HTMLElement} */ (/** @type {Element} */ (e.target).closest(selector));

/**
 * Адрес файла со спрайтом иконок.
 *
 * Берём из уже стоящей на странице ссылки: в собранной версии в имени файла
 * хеш, и угадать его из JS неоткуда — строки внутри шаблонов Vite не
 * переписывает. Живёт здесь, а не в галерее: тем же спрайтом пользуется
 * увеличение снимка, а импортировать его из галереи нельзя — галерея сама
 * зовёт увеличение, вышел бы круг.
 *
 * @returns {string} Адрес файла или пустая строка, если ссылки на странице нет.
 */
export const spriteHref = () =>
  document.querySelector('use[href*="spritemap"]')?.getAttribute('href').split('#')[0] ?? '';
