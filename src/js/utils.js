// ─── Утилиты ───

// Форматирует число как цену в рублях: 78990 -> «78 990 ₽».
// Между числом и ₽ стоит неразрывный пробел (код U+00A0), чтобы они не
// переносились на разные строки.
export const fmt = (n) => `${n.toLocaleString('ru-RU')}\u00A0₽`;

// Режим прокрутки с учётом настройки ОС «уменьшить движение».
export const smooth = matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth';

// Экранирует текст, который попадает в HTML-шаблоны карточек. Пока товары
// лежали в коде, этого не требовалось — там всё было написано нами. Из CMS
// приходит что угодно: кавычка в названии «Диван "Зевс"» разорвала бы атрибут
// alt, а угловая скобка — всю разметку карточки.
export const esc = (v) => String(v).replace(/[&<>"']/g, (c) => `&#${ c.charCodeAt(0) };`);

// Адрес спрайта берём из уже стоящей на странице ссылки: в собранной версии
// в имени файла хеш, и угадать его из JS неоткуда — строки внутри шаблонов
// Vite не переписывает. Живёт здесь, а не в галерее: тем же спрайтом
// пользуется увеличение снимка, а импортировать его из галереи нельзя —
// галерея сама зовёт увеличение, вышел бы круг.
export const spriteHref = () =>
  document.querySelector('use[href*="spritemap"]')?.getAttribute('href').split('#')[0] ?? '';
