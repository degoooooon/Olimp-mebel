// ─── Адрес страницы товара ───
//
// На живом сайте адрес приходит от WordPress готовым, полем url: слаг может
// быть каким угодно, а вид постоянных ссылок настраивается в админке —
// собрать такой адрес в браузере неоткуда.
//
// В статической сборке WordPress нет и страниц товаров тоже нет: там открыть
// можно только макет tovar.html, и адрес собирается из номера товара.
// Поэтому фронтенд берёт url, если он есть, и падает обратно на макет,
// если его нет. Так одна и та же карточка работает в обоих случаях.

/**
 * @param {import('./data.js').Product} p Товар.
 * @returns {string} Адрес его страницы.
 */
export const productUrl = (p) => p.url ?? `./tovar.html?tovar=${ encodeURIComponent(p.id) }`;
