// ─── Адрес товара ───
//
// Отдельных страниц у товаров пока нет: их выдаёт WordPress, а тема сейчас
// не трогается. Поэтому адрес товара — параметр к главной: `?tovar=101`.
//
// Такой адрес работает везде без единой правки на сервере. Путь не меняется,
// значит и статика, и WordPress отдают ту же главную страницу, а скрипт
// по параметру сразу открывает нужный товар.
//
// Зачем это вообще: заказы у склада принимают звонком и в мессенджере.
// Покупатель спрашивает «а есть такой диван» — и в ответ нужно отправить
// ссылку на конкретный товар. Пока адрес был один на весь сайт, отправлять
// было нечего: человек получал главную и искал сам.
//
// Когда появятся настоящие страницы, менять придётся только этот файл:
// URL станет `/tovar/divan-zevs/`, остальной код не заметит разницы.

const PARAM = 'tovar';

/**
 * Адрес карточки товара.
 *
 * encodeURIComponent обязателен: id приходит из CMS, и хотя сейчас это всегда
 * число из базы, договор формата чисел не гарантирует. Незакодированное
 * значение с кавычкой разорвало бы атрибут href.
 */
export const productUrl = (id) => `?${ PARAM }=${ encodeURIComponent(id) }`;

/**
 * Какой товар просят в адресе. Возвращает id строкой или null.
 */
export function idFromUrl() {
  return new URLSearchParams(location.search).get(PARAM);
}

/**
 * Есть ли в истории наша запись. По ней видно, открыли окно нажатием
 * на карточку или пришли по ссылке сразу на товар: в первом случае закрытие
 * должно вернуть назад, во втором возвращаться некуда.
 */
export const pushedByUs = () => Boolean(history.state && history.state[PARAM]);

/**
 * Кладёт товар в адрес и в историю.
 */
export function pushProduct(id) {
  history.pushState({ [PARAM]: id }, '', productUrl(id));
}

/**
 * Убирает товар из адреса, не добавляя записи в историю. Нужно, когда
 * закрывать нечего — человек открыл ссылку на товар первой же страницей.
 */
export function dropProduct() {
  history.replaceState(null, '', location.pathname);
}
